  List<FoodItem> get allFoods => _foods;

  /// Get foods by category
  List<FoodItem> getByCategory(String category) {
    return _foods.where((f) => f.category == category).toList();
  }

  /// Search foods by name
  List<FoodItem> search(String query) {
    if (query.isEmpty) return [];
    final lowerQuery = query.toLowerCase();
    return _foods.where((f) => 
      f.name.toLowerCase().contains(lowerQuery) ||
      (f.category?.toLowerCase().contains(lowerQuery) ?? false)
    ).toList();
  }

