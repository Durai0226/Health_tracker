/// Built-in exercise library with 50+ exercises
/// Organized by body part for easy access
class ExerciseLibrary {
  static final ExerciseLibrary _instance = ExerciseLibrary._internal();
  factory ExerciseLibrary() => _instance;
  ExerciseLibrary._internal();

  /// Get all exercises
  List<Exercise> get allExercises => _exercises;

  /// Get exercises by body part
  List<Exercise> getByBodyPart(BodyPart bodyPart) {
    return _exercises.where((e) => 
      e.primaryBodyPart == bodyPart || 
      e.secondaryBodyParts.contains(bodyPart)
    ).toList();
  }

  /// Get exercises by difficulty
  List<Exercise> getByDifficulty(ExerciseDifficulty difficulty) {
    return _exercises.where((e) => e.difficulty == difficulty).toList();
  }

  /// Get exercise by ID
  Exercise? getById(String id) {
    try {
      return _exercises.firstWhere((e) => e.id == id);
    } catch (_) {
      return null;
    }
  }

  /// Search exercises by name
  List<Exercise> search(String query) {
    final lowerQuery = query.toLowerCase();
    return _exercises.where((e) => 
      e.name.toLowerCase().contains(lowerQuery) ||
      e.description.toLowerCase().contains(lowerQuery)
    ).toList();
  }

  /// Get body part workout count
  Map<BodyPart, int> get bodyPartCounts {
    final counts = <BodyPart, int>{};
    for (final bodyPart in BodyPart.values) {
      counts[bodyPart] = getByBodyPart(bodyPart).length;
    }
    return counts;
  }

